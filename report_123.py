"""Markdown tables for the 1-2-3 study -> RESULTS_123.md"""
import numpy as np
import pandas as pd

D = "results/onetwothree"
t = pd.read_csv(f"{D}/trades.csv")
S = pd.read_csv(f"{D}/summary.csv")
P = pd.read_csv(f"{D}/summary_by_period.csv")
Y = pd.read_csv(f"{D}/yearly.csv")
K = pd.read_csv(f"{D}/skips.csv")
DIR = pd.read_csv(f"{D}/by_direction.csv")
order = list(S.variant)
MAIN = "D | 15m | all"
L = lambda v: v.replace(" | ", " · ")

tt = {}
for v, g in t.groupby("variant"):
    u = g.pnl_usd.values
    tt[v] = u.mean() / (u.std(ddof=1) / np.sqrt(len(u)))


def row(r, lab):
    flag = " ⚠️" if r.trades < 300 else ""
    above = "yes" if r.ci95_lo > 0.5 else ("no" if r.ci95_hi < 0.5 else "not distinguishable")
    return (f"| {lab}{flag} | {int(r.trades)} | {int(r.wins)} | {int(r.losses)} | {r.win_rate:.1%} "
            f"({r.ci95_lo:.1%}–{r.ci95_hi:.1%}) | {r.binom_p_vs_50:.2g} | {above} | {r.breakeven_win_rate:.1%} | "
            f"{r.avg_win_r:+.2f} / {r.avg_loss_r:+.2f} | {r.avg_win_usd:+.0f} / {r.avg_loss_usd:+.0f} | "
            f"{r.gross_r:+.3f} | {r.expectancy_r:+.3f} | {r.net_usd:+,.0f} | {r.profit_factor:.2f} | "
            f"{r.max_dd_usd:,.0f} / {r.max_dd_r:.0f}R |")


HDR = ("| Variant | Trades | Wins | Losses | Win rate (95% CI) | Binomial p vs 50% | Win rate > 50%? | Breakeven win rate | "
       "Avg win / loss (R) | Avg win / loss ($) | Gross R | Expectancy R (net) | Net $ | PF ($) | Max DD $ / R |\n"
       "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
md = ["# 1-2-3 method: full results\n",
      "Generated by `report_123.py`. 1 MNQ ($2/pt), $1.24 per round turn, 1 tick of slippage on entries, stop exits and the "
      "5-day market exit. Variant names read *HTF zone · target · entry hours*. Main = **D · 15m · all**. "
      "Breakeven win rate = avg loss R ÷ (avg win R + avg loss R). ⚠️ = fewer than 300 trades.\n",
      "## Full period (2010-11 → 2026-11)\n", HDR]
md += [row(r, L(r.variant)) for r in S.itertuples()]
md.append("\n## Profitability check: t-statistic of mean net $ per trade (|t| < 2 = not distinguishable from zero)\n")
md.append("| Variant | Net $ | Expectancy $/trade | t | Profitable after costs? |\n|---|---|---|---|---|")
for r in S.itertuples():
    verdict = "yes" if tt[r.variant] > 2 else ("no (loses)" if r.net_usd < 0 else "no: positive but not distinguishable from zero")
    md.append(f"| {L(r.variant)} | {r.net_usd:+,.0f} | {r.expectancy_usd:+.2f} | {tt[r.variant]:+.2f} | {verdict} |")
for per in ("dev 2010-2020", "holdout 2021-2026"):
    md += [f"\n## {per}\n", HDR]
    md += [row(r, L(r.variant)) for r in P[P.period == per].itertuples()]
md.append("\n## Skips (each counted once, in the order the rules are checked)\n")
md.append("| Variant | Triggers | Taken | No 15m target | Trade already open | 2-per-day limit | Entry beyond stop | Outside NY session |")
md.append("|---|---|---|---|---|---|---|---|")
for r in K.itertuples():
    md.append(f"| {L(r.variant)} | {r.triggers} | {r.taken} | {r.no_15m_target} | {r.open_trade} | {r.day_limit} | "
              f"{r.entry_beyond_stop} | {r.outside_session} |")
md.append("\n## By direction\n\n| Variant | Direction | Trades | Win rate | Breakeven | Expectancy R | Net $ |\n|---|---|---|---|---|---|---|")
for r in DIR.itertuples():
    md.append(f"| {L(r.variant)} | {r.direction} | {int(r.trades)} | {r.win_rate:.1%} | {r.breakeven_win_rate:.1%} | "
              f"{r.expectancy_r:+.3f} | {r.net_usd:+,.0f} |")
md.append("\n## Year by year (trades / win rate / expectancy R / net $)\n")
for grp in ("D", "4H", "D+4H"):
    vs = [v for v in order if v.startswith(grp + " |")]
    md.append(f"\n**{grp} zones**\n\n| Year | " + " | ".join(L(v) for v in vs) + " |\n|" + "---|" * (len(vs) + 1))
    for y in sorted(Y.year.unique()):
        cells = []
        for v in vs:
            r = Y[(Y.variant == v) & (Y.year == y)]
            cells.append("-" if r.empty else f"{int(r.trades.iloc[0])} / {r.win_rate.iloc[0]:.0%} / "
                         f"{r.expectancy_r.iloc[0]:+.2f} / {r.net_usd.iloc[0]:+,.0f}")
        md.append(f"| {y} | " + " | ".join(cells) + " |")
open("RESULTS_123.md", "w").write("\n".join(md) + "\n")
print(len(md), "lines")
