"""Markdown tables for the SMT study (results/smt/*.csv) -> RESULTS_SMT.md"""
import numpy as np
import pandas as pd

D = "results/smt"
t = pd.read_csv(f"{D}/trades.csv")
S = pd.read_csv(f"{D}/summary.csv")
P = pd.read_csv(f"{D}/summary_by_period.csv")
Y = pd.read_csv(f"{D}/yearly.csv")
B = pd.read_csv(f"{D}/by_stop_size.csv")
DIR = pd.read_csv(f"{D}/by_direction.csv")
F = pd.read_csv(f"{D}/funnel.csv", index_col=0)["count"]
BE = pd.read_csv(f"{D}/breakeven_diagnostics.csv", index_col=0).iloc[:, 0]
V = ["main", "no_breakeven", "no_min_2R"]
md = ["# SMT model: full results\n",
      "Generated by `report_smt.py`. 1 MNQ ($2/pt), $1.24 per round turn, 1 tick of slippage on entries, stop exits "
      "(including break-even stops) and the 16:00 flatten. R = net $ ÷ planned risk $. ⚠️ = fewer than 300 trades "
      "(every row here). PF is shown both on R and on dollars.\n"]


def table(df, keycol=None):
    hdr = ("| " + (f"{keycol} | " if keycol else "") + "Variant | Trades | Wins | Losses | BE | Flat 16:00 | Win% (BE = non-win) | "
           "Win% (excl. BE) | Gross R | Net R (avg realized) | Exp $/trade | Net $ | PF (R) | PF ($) | Max DD R | Max DD $ |")
    out = [hdr, "|" + "---|" * (hdr.count("|") - 1)]
    for _, r in df.iterrows():
        k = f"{r[keycol]} | " if keycol else ""
        out.append(f"| {k}{r.variant} ⚠️ | {int(r.trades)} | {int(r.wins)} | {int(r.losses)} | {int(r.breakevens)} | "
                   f"{int(r.flattened_1600)} | {r.win_rate_be_as_nonwin:.1%} | {r.win_rate_excl_be:.1%} | {r.gross_r:+.2f} | "
                   f"{r.net_r:+.2f} | {r.expectancy_usd:+.2f} | {r.net_usd:+,.0f} | {r.profit_factor_r:.2f} | "
                   f"{r.profit_factor_usd:.2f} | {r.max_dd_r:.1f} | {r.max_dd_usd:,.0f} |")
    return out


md += ["## Full period (2010-11 → 2026-11)\n"] + table(S)
md += ["\n## Development (2010–2020) vs hold-out (2021–2026, run once)\n"] + table(P, "period")

md.append("\n## Significance and concentration\n")
md.append("| Variant | t-stat of mean net R | Bootstrap P(mean R ≤ 0) | t-stat of mean $ | Bootstrap P(mean $ > 0) | Three best trades (R) | Net R without them |")
md.append("|---|---|---|---|---|---|---|")
rng = np.random.default_rng(0)
for v in V:
    x = t[t.variant == v]
    r, u = x.r.values, x.pnl_usd.values
    bs = np.array([rng.choice(r, len(r)).mean() for _ in range(10000)])
    bu = np.array([rng.choice(u, len(u)).mean() for _ in range(10000)])
    top = np.sort(r)[::-1]
    md.append(f"| {v} | {r.mean() / (r.std(ddof=1) / np.sqrt(len(r))):+.2f} | {(bs <= 0).mean():.2f} | "
              f"{u.mean() / (u.std(ddof=1) / np.sqrt(len(u))):+.2f} | {(bu > 0).mean():.2f} | "
              f"{', '.join(f'{z:+.1f}' for z in top[:3])} | {top[3:].sum():+.1f} |")

md.append("\n## Break-even rule diagnostics (main vs the same entries without break-even)\n")
md.append("| Item | Value |\n|---|---|")
for k, v in BE.items():
    md.append(f"| {k.replace('_', ' ')} | {float(v):.2f} |" if "net_r" in k else f"| {k.replace('_', ' ')} | {int(float(v))} |")

md.append("\n## Each variant vs main\n")
md.append("| Variant | Trades | Win% (BE = non-win) | Net R/trade | Δ net R vs main | Net $ | Δ net $ vs main | Hold-out net R |")
md.append("|---|---|---|---|---|---|---|---|")
m = S.set_index("variant")
ph = P[P.period.str.startswith("holdout")].set_index("variant")
for v in V:
    r = m.loc[v]
    md.append(f"| {v} | {int(r.trades)} | {r.win_rate_be_as_nonwin:.1%} | {r.net_r:+.3f} | {r.net_r - m.loc['main'].net_r:+.3f} | "
              f"{r.net_usd:+,.0f} | {r.net_usd - m.loc['main'].net_usd:+,.0f} | {ph.loc[v].net_r:+.3f} |")

md.append("\n## By stop size (planned risk in NQ points)\n")
md.append("| Variant | Stop | Trades | Wins | BE | Net R/trade | Exp $/trade | Net $ |\n|---|---|---|---|---|---|---|---|")
for _, r in B.iterrows():
    md.append(f"| {r.variant} | {r.stop_bucket} | {int(r.trades)} | {int(r.wins)} | {int(r.breakevens)} | {r.net_r:+.2f} | "
              f"{r.expectancy_usd:+.2f} | {r.net_usd:+,.0f} |")

md.append("\n## By direction\n")
md.append("| Variant | Direction | Trades | Wins | BE | Net R/trade | Net $ |\n|---|---|---|---|---|---|---|")
for _, r in DIR.iterrows():
    md.append(f"| {r.variant} | {r.direction} | {int(r.trades)} | {int(r.wins)} | {int(r.breakevens)} | {r.net_r:+.2f} | {r.net_usd:+,.0f} |")

md.append("\n## Year by year (trades / wins / BE / net R per trade / net $)\n")
md.append("| Year | " + " | ".join(V) + " |\n|" + "---|" * (len(V) + 1))
for y in sorted(Y.year.unique()):
    cells = []
    for v in V:
        r = Y[(Y.year == y) & (Y.variant == v)]
        cells.append("-" if r.empty else
                     f"{int(r.trades.iloc[0])} / {int(r.wins.iloc[0])} / {int(r.breakevens.iloc[0])} / {r.net_r.iloc[0]:+.2f} / {r.net_usd.iloc[0]:+,.0f}")
    md.append(f"| {y} | " + " | ".join(cells) + " |")

md.append("\n## Setup funnel (days and setups surviving each rule, both directions)\n")
md.append("| Step | Count |\n|---|---|")
for k, v in F.items():
    md.append(f"| {k} | {int(v)} |")
open("RESULTS_SMT.md", "w").write("\n".join(md) + "\n")
print("\n".join(md[:40]))
